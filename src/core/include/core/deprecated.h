#pragma once

/*! \brief Macro to allow usage of deprecated declarations
 *  \param _reason The reason why this usage should be allowed for documentation
 */
#define ALLOW_DEPRECATED_BECAUSE(_reason) \
    _Pragma("GCC diagnostic push") \
    _Pragma("GCC diagnostic ignored \"-Wdeprecated-declarations\"")

#define ALLOW_DEPRECATED_END() \
    _Pragma("GCC diagnostic pop")
